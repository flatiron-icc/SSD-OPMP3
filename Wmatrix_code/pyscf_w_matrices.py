"""The eight W matrices of the paper from the MP amplitudes
generated by one linearized CCSD iteration (mp3.py).

For n = 2, 3 and spin sigma, with c^(1), c^(2) the first- and second-order
doubles amplitudes,

    W^SS(n)_ij = 1/8 sum_kab [c^(n-1)_ikab <jk||ab> + (i <-> j)]   (k, a, b of spin sigma)
    W^OS(n)_ij = 1/4 sum_kab [c^(n-1)_ikab <jk|ab>  + (i <-> j)]   (k, b of the other spin)

saved as W{n}{alpha,beta}_{ss,os}.npy, so Tr W2 is the MP2 doubles energy
and Tr W3 the MP3 doubles energy.  The OP-MP3, SOP-MP3 and SSD-OPMP3
correlation energies (Eqs. 14, 21 and 22) are computed from them.
An electric field enters only through the semicanonical orbitals and orbital energies.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
from pyscf import cc, lib, scf
from pyscf.cc.ccsd import BLKMIN
from scipy.linalg import pinv

import mp3
from pyscf_dft import handle_basis_core
from workflow_common import (
    W2_LABELS,
    W3_LABELS,
    DEFAULT_X_SS,
    SemicanonicalResult,
    WorkflowPaths,
    derive_output_paths,
)


def _reference(mol, sc: SemicanonicalResult, df: bool, auxbasis, memory: int):
    """The seeded HF object the CCSD machinery needs: RHF for a closed-shell
    reference and UHF otherwise, carrying the semicanonical orbitals; it is
    never run through ``kernel``."""
    cls = scf.RHF if sc.closed_shell else scf.UHF
    mf = cls(mol).density_fit(auxbasis=handle_basis_core(auxbasis, mol)) if df else cls(mol)
    mf.mo_coeff   = sc.mo_coeff
    mf.mo_occ     = sc.mo_occ
    mf.mo_energy  = sc.mo_energy
    mf.e_tot      = sc.e_hf_from_density
    mf.max_memory = float(memory)
    mf.chkfile    = None
    return mf


# ---------------------------------------------------------------------------
# W matrices (the paper's Eqs. 17-18)
# ---------------------------------------------------------------------------

def _w_matrices_u(c1: tuple, c2: tuple, eris) -> dict[str, np.ndarray]:
    """Eqs. 17 and 18, unrestricted."""
    def same_spin(ovov):
        g = np.asarray(ovov)
        return g.transpose(0, 2, 1, 3) - g.transpose(0, 2, 3, 1)

    g_aa = same_spin(eris.ovov)
    g_bb = same_spin(eris.OVOV)
    g_ab = np.asarray(eris.ovOV).transpose(0, 2, 1, 3)
    out = {}
    for labels, (caa, cab, cbb) in ((W2_LABELS, c1), (W3_LABELS, c2)):
        blocks = (0.125 * lib.einsum("ikab,jkab->ij", caa, g_aa),
                  0.25 * lib.einsum("ikab,jkab->ij", cab, g_ab),
                  0.125 * lib.einsum("ikab,jkab->ij", cbb, g_bb),
                  0.25 * lib.einsum("ikab,ilab->kl", cab, g_ab))
        for label, x in zip(labels, blocks):
            out[label] = x + x.T
    return out


def _w_matrices_r(c1: np.ndarray, c2: np.ndarray, eris,
                  max_memory: float) -> dict[str, np.ndarray]:
    """Eqs. 17 and 18, closed shell, reading <jk|ab> in blocks of virtual
    orbitals.  With X_ij = sum_kab c_ikab <jk|ab> and
    Y_ij = sum_kab c_kiab <jk|ab>: W^SS = 1/4 [(X - Y) + (X - Y)^T],
    W^OS = 1/4 [X + X^T], and the beta blocks equal the alpha ones.
    """
    nocc, nvir = c1.shape[1:3]
    mem = max(0, max_memory - lib.current_memory()[0])
    blksize = int(min(nvir, max(BLKMIN, mem * .3e6 / 8 / (nocc**2 * nvir + 1))))
    x = np.zeros((2, nocc, nocc))
    y = np.zeros((2, nocc, nocc))
    for p0, p1 in lib.prange(0, nvir, blksize):
        ovov = np.asarray(eris.ovov[:, p0:p1])
        for n, c in enumerate((c1, c2)):
            x[n] += lib.einsum("ikab,jakb->ij", c[:, :, p0:p1], ovov)
            y[n] += lib.einsum("kiab,jakb->ij", c[:, :, p0:p1], ovov)
        ovov = None
    out = {}
    for labels, xn, yn in zip((W2_LABELS, W3_LABELS), x, y):
        ss = 0.25 * ((xn - yn) + (xn - yn).T)
        os_ = 0.25 * (xn + xn.T)
        for label, w in zip(labels, (ss, os_, ss, os_)):
            out[label] = w.copy()
    return out


def _compute_w(mol, sc: SemicanonicalResult, ncore: int, df: bool, auxbasis,
               memory: int, log_fh=None) -> dict[str, np.ndarray]:
    """The eight active-space W matrices, from the CC object PySCF builds for
    the reference (pyscf.cc.CCSD: RCCSD for a closed-shell reference, UCCSD
    otherwise, density-fitted with df)."""
    # PySCF objects take their stdout from mol when built: the SCF, DF and
    # CC objects below all log to log_fh.
    stdout_orig = mol.stdout
    if log_fh is not None:
        mol.stdout = log_fh
    try:
        mf = _reference(mol, sc, df=df, auxbasis=auxbasis, memory=memory)
        mycc = cc.CCSD(mf, frozen=int(ncore) or None)
        eris = mp3.make_eris(mycc, sc.mo_energy)
        c1, c2 = mp3.mp23_amplitudes(mycc, eris)
        if sc.closed_shell:
            return _w_matrices_r(c1, c2, eris, mycc.max_memory)
        return _w_matrices_u(c1, c2, eris)
    finally:
        mol.stdout = stdout_orig


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _pade(w2: np.ndarray, w3: np.ndarray, x: float = 1.0) -> float:
    """Tr[W2 (W2 - x W3)^-1 W2] (Eq. 13); with the pseudo-inverse, an empty or
    zero block gives 0."""
    return float(np.trace(w2 @ pinv(w2 - x * w3) @ w2))


def _zero_w_matrices(nact_a: int, nact_b: int) -> dict[str, np.ndarray]:
    """Zero W matrices over the active occupied orbitals of each spin."""
    return {label: np.zeros((n, n))
            for labels in (W2_LABELS, W3_LABELS)
            for label, n in zip(labels, (nact_a, nact_a, nact_b, nact_b))}


def _save_results(paths: WorkflowPaths, matrices: dict[str, np.ndarray],
                  x_ss: float = DEFAULT_X_SS) -> dict:
    """Write the eight W matrices to .npy; return their paths, the same-spin,
    opposite-spin and total traces of W2 and W3, and the OP-MP3, SOP-MP3 and
    SSD-OPMP3 (at x_ss) correlation energies."""
    files: dict[str, str] = {}
    for label, matrix in matrices.items():
        np.save(paths.w_matrix(label), matrix)
        files[label] = str(paths.w_matrix(label))
    out: dict = {"files": files}
    for n, labels in ((2, W2_LABELS), (3, W3_LABELS)):
        ss = float(np.trace(matrices[labels[0]]) + np.trace(matrices[labels[2]]))
        os_ = float(np.trace(matrices[labels[1]]) + np.trace(matrices[labels[3]]))
        out.update({f"Tr(W{n}_ss)": ss, f"Tr(W{n}_os)": os_, f"Tr(W{n})": ss + os_})

    def pade(kinds, x=1.0):   # Eq. 13 for each spin, summed over alpha and beta
        return sum(_pade(sum(matrices[f"W2{s}_{k}"] for k in kinds),
                         sum(matrices[f"W3{s}_{k}"] for k in kinds), x)
                   for s in ("alpha", "beta"))

    out["OP-MP3"] = pade(["ss", "os"])                          # Eq. 14
    out["SOP-MP3"] = pade(["ss"]) + pade(["os"])                # Eq. 21
    out["SSD-OPMP3"] = pade(["ss"], x_ss) + pade(["os"])        # Eq. 22
    out["SSD-OPMP3 x_ss"] = float(x_ss)
    return out


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------

def run_pyscf_w_matrices(
    mol,
    semicanonical: SemicanonicalResult,
    input_path:    str | Path,
    ncore:         int,
    *,
    df:            bool = False,
    auxbasis:      str | None = None,
    memory:        int = 16000,
    output_paths:  WorkflowPaths | None = None,
    x_ss:          float = DEFAULT_X_SS,
) -> dict:
    """Compute and save the W2 and W3 matrices, each (nact, nact) over the
    occupied orbitals of its spin that are not among the ncore frozen ones;
    ``x_ss`` is that of the returned SSD-OPMP3 energy.
    """
    ncore = int(ncore)
    if ncore < 0:
        raise ValueError("ncore must be non-negative")

    paths          = derive_output_paths(input_path) if output_paths is None else output_paths
    if semicanonical.closed_shell:
        nocc_a = nocc_b = semicanonical.nocc
    else:
        nocc_a, nocc_b = semicanonical.nocc
    nact_a         = nocc_a - ncore
    nact_b         = nocc_b - ncore

    # Checked first: too many frozen orbitals would otherwise pass as zero correlation.
    if nact_a < 0 or nact_b < 0:
        raise ValueError(
            "Frozen-core count exceeds the occupied space "
            f"(ncore={ncore}, nocc_alpha={nocc_a}, nocc_beta={nocc_b})."
        )

    if nact_a + nact_b < 2:
        return _save_results(paths, _zero_w_matrices(nact_a, nact_b), x_ss)

    with open(paths.pyscf_output, "a", encoding="utf-8", buffering=1) as log_fh:
        w = _compute_w(
            mol, semicanonical, ncore=ncore,
            df=df, auxbasis=auxbasis, memory=memory,
            log_fh=log_fh,
        )

    return _save_results(paths, w, x_ss)
